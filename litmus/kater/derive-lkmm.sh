#!/usr/bin/env bash
# Derive an *includable* LKMM model from the one kater ships.
#
# Why this exists: kater rejects the internal (`-imm`) relations that
# kat/lkmm2.kat is written over --
#
#     kat/lkmm2.kat:3.14-19: forbidden use of internal relation (mo-imm)
#
# -- and it does so in every mode, including when lkmm2.kat is the file kater
# was handed. So the shipped file does not load at all against this image, and
# LKMM is neither a checking target nor a comparison operand until it is
# restated. Every `-imm` relation lkmm2.kat defines its own names from (po,
# po-loc, mo, fr, rmw, ctrl, addr, data) is already in kater's builtin theory,
# so the restatement is mechanical: drop the redefinitions and use the builtins.
#
# This is a *script* rather than a checked-in .kat on purpose: kater's models are
# GPL-3.0 and this dataset is BSD-3, so the derived file -- a derivative work of
# lkmm2.kat -- is generated into a scratch directory at run time and never
# vendored here, exactly as the queries include kat/*.kat from inside the image
# rather than copying them.
#
# Usage:  ./derive-lkmm.sh OUTFILE [IMAGE]
set -eu
OUT=${1:?usage: derive-lkmm.sh OUTFILE [IMAGE]}
IMAGE=${2:-genmc/kater}
DOCKER=${DOCKER:-docker}

{
  cat <<'HEADER'
// GENERATED by litmus/kater/derive-lkmm.sh from kat/lkmm2.kat inside the kater
// image -- do not edit, and do not commit: it is a derivative of a GPL-3.0 file.
//
// Difference from the shipped model, in full:
//   * the `-imm` redefinitions of po, po-loc, mo, fr, rmw, ctrl, addr and data
//     are dropped, so those names resolve to kater's builtin theory instead;
//   * the two `mo-imm` premises are restated over mo;
//   * `save[ppo]` (export-mode syntax) becomes a plain `let`;
//   * `hb-alt` is dropped -- it is an unused alternative formulation, and it is
//     stated over `int`, which this kater has no builtin for;
//   * the consistency axioms are commented out, as kat/c11-old.kat and
//     kat/rc11.kat also do: a comparison operand supplies relation definitions,
//     and the query states what must hold of them.
// The LKMM-specific event kinds are declared here because they are outside
// kater's builtin predicate set; the disjointness mirrors kat/arm8.kat's
// treatment of its own extra fence predicates.

predicate Frmb
predicate Fwmb
predicate Fba
predicate Faa
predicate Faul
predicate UL
predicate LR
predicate Marked

disjoint R # W # Frmb # Fwmb # Fba # Faa # Faul

HEADER
  "$DOCKER" run --rm --entrypoint cat "$IMAGE" /root/kater/kat/lkmm2.kat \
  | sed -e 's/mo-imm/mo/g' \
        -e '/^let po = /d' \
        -e '/^let po-loc = /d' \
        -e '/^let mo = /d' \
        -e '/^let fr = /d' \
        -e '/^let rmw = /d' \
        -e '/^let ctrl = /d' \
        -e '/^let addr = /d' \
        -e '/^let data = /d' \
        -e 's/^save\[ppo\] ppo =/let ppo =/' \
        -e 's/^coherence /\/\/ coherence /' \
        -e 's/^acyclic /\/\/ acyclic /' \
        -e 's/^check  */\/\/ check /' \
  | awk '/^let hb-alt =/{skip=1} skip && /^$/{skip=0} !skip'
} > "$OUT"

# The whole point is that no -imm survives; fail loudly rather than emit a file
# that will be rejected further down the line.
if sed 's|//.*||' "$OUT" | grep -q -- '-imm'; then
  echo "derive-lkmm.sh: internal relations survived the rewrite in $OUT" >&2
  exit 1
fi
